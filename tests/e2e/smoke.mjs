// Protocol smoke test: real supabase-js against the gateway + real schema.
import { createClient } from '@supabase/supabase-js';
import assert from 'node:assert/strict';
const URL = process.env.GW ?? 'http://localhost:54321';
const mk = () => createClient(URL, 'local-anon', { auth: { persistSession: false } });
const a = mk(), b = mk();
const ea = `a${Date.now()}@test.local`, eb = `b${Date.now()}@test.local`;
assert.ifError((await a.auth.signUp({ email: ea, password: 'secret123' })).error);
assert.ifError((await b.auth.signUp({ email: eb, password: 'secret123' })).error);
const ua = (await a.auth.getUser()).data.user.id;
const prof = await a.from('profiles').select('*').maybeSingle();
assert.ifError(prof.error); assert.equal(prof.data.id, ua);
const ins = await a.from('tasks').upsert({ id: crypto.randomUUID(), user_id: ua, title: 'Buy groceries' }, { onConflict: 'id' });
assert.ifError(ins.error);
const mine = await a.from('tasks').select('id,title').eq('title', 'Buy groceries').order('created_at');
assert.equal(mine.data.length, 1);
const theirs = await b.from('tasks').select('*');
assert.equal(theirs.data.length, 0, 'RLS: B sees none of A tasks');
const steal = await b.from('tasks').insert({ id: crypto.randomUUID(), user_id: ua, title: 'x' });
assert.ok(steal.error, 'RLS: B cannot insert as A');
const upd = await b.from('tasks').update({ title: 'hacked' }).eq('id', mine.data[0].id);
const still = await a.from('tasks').select('title').eq('id', mine.data[0].id).single();
assert.equal(still.data.title, 'Buy groceries', 'RLS: B cannot update A');
const anon = await mk().from('tasks').select('*');
assert.ok(anon.error || anon.data.length === 0, 'anon gets nothing');
await a.auth.signOut();
const relog = await a.auth.signInWithPassword({ email: ea, password: 'secret123' });
assert.ifError(relog.error);
const bad = await a.auth.signInWithPassword({ email: ea, password: 'wrong' });
assert.ok(bad.error);
console.log('gateway smoke: all assertions passed');
